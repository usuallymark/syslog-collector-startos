// Builds rsyslog's configuration from the receiver settings. main.ts writes
// it into the container on every start; it is never stored on the volume.
//
// Each message becomes one line in /data/logs/<sender>/<YYYY-MM-DD>.log:
//
//   <received time, RFC 3339> <sender IP> <facility>.<severity> <hostname> <tag> <message>
//
// The day of the file name and the received time both follow the time zone
// chosen in Configure Receiver.

export type RsyslogOptions = {
  port: number
  udp: boolean
  tcp: boolean
  folderNaming: 'hostname' | 'ip'
  logsDir: string
}

export function rsyslogConf(o: RsyslogOptions): string {
  // secpath-replace turns "/" into "_" and makes ".", ".." and empty names
  // safe, so a sender cannot write outside its own folder.
  const folder =
    o.folderNaming === 'ip'
      ? '%fromhost-ip:::secpath-replace%'
      : '%hostname:::lowercase,secpath-replace%'

  const inputs: string[] = []
  if (o.udp) {
    inputs.push(
      'module(load="imudp")',
      `input(type="imudp" port="${o.port}" ruleset="remote")`,
    )
  }
  if (o.tcp) {
    // imtcp accepts both newline-terminated and octet-counted (RFC 6587)
    // framing on the same port.
    inputs.push(
      'module(load="imtcp" maxSessions="500")',
      `input(type="imtcp" port="${o.port}" ruleset="remote")`,
    )
  }

  return `# Generated by the Log Collector package on every start. Do not edit:
# change the settings in Configure Receiver instead.

global(
  workDirectory="/var/spool/rsyslog"
  maxMessageSize="64k"
)

${inputs.join('\n')}

template(name="dayFile" type="string"
  string="${o.logsDir}/${folder}/%$year%-%$month%-%$day%.log")

template(name="line" type="string"
  string="%timegenerated:::date-rfc3339% %fromhost-ip% %syslogfacility-text%.%syslogseverity-text% %hostname% %syslogtag%%msg:::sp-if-no-1st-sp%%msg:::drop-last-lf%\\n")

# Messages from the network: one file per sender per day.
ruleset(name="remote") {
  action(
    type="omfile"
    dynaFile="dayFile"
    template="line"
    createDirs="on"
    dirCreateMode="0755"
    fileCreateMode="0644"
    dynaFileCacheSize="200"
    closeTimeout="10"
  )
}

# rsyslog's own messages (errors, warnings) go to stderr, which StartOS shows
# in the service logs.
`
}
