// Builds rsyslog's configuration from the receiver settings. main.ts writes
// it into the container on every start; it is never stored on the volume.
//
// Each message becomes one line in /data/logs/<sender>/<YYYY-MM-DD>.log:
//
//   <received time, RFC 3339> <sender IP> <facility>.<severity> <hostname> <program>[<pid>]: <message>
//
// The line looks the same whether the device sent RFC 3164 (BSD) or RFC 5424
// (IETF) syslog. The day of the file name and the received time both follow
// the time zone chosen in Configure Receiver.

import type { FolderNaming } from './fileModels/settings.json'
import { allowCondition } from './senders'

export type RsyslogOptions = {
  port: number
  udp: boolean
  tcp: boolean
  folderNaming: FolderNaming
  logsDir: string
  // Allow-list entries; empty accepts every sender.
  allowedSenders: string[]
  // Where impstats writes the per-IP reject counters every minute.
  statsFile: string
}

// The sender folder, set in $.folder:
// - full: the hostname the device sent
// - short: the hostname up to its first dot (vp2430.internal -> vp2430),
//   except when the "hostname" is an IP address, which is kept whole
// - ip: the address the message came from
const FOLDER_RULES: Record<FolderNaming, string> = {
  full: 'set $.folder = $hostname;',
  short: `if re_match($hostname, '^[0-9.]+$') or re_match($hostname, ':') then {
    set $.folder = $hostname;
  } else {
    set $.folder = field($hostname, 46, 1);
  }`,
  ip: 'set $.folder = $fromhost-ip;',
}

export function rsyslogConf(o: RsyslogOptions): string {
  const inputs: string[] = []
  if (o.udp) {
    inputs.push(
      'module(load="imudp")',
      `input(type="imudp" port="${o.port}" ruleset="remote")`,
    )
  }
  if (o.tcp) {
    // imtcp accepts both newline-terminated and octet-counted (RFC 6587)
    // framing on the same port.
    inputs.push(
      'module(load="imtcp" maxSessions="500")',
      `input(type="imtcp" port="${o.port}" ruleset="remote")`,
    )
  }

  const allow = allowCondition(o.allowedSenders)
  // A rejected message is counted per source IP, in memory, and dropped:
  // nothing of it reaches the disk, so a flood cannot fill it.
  const allowList = allow
    ? `
module(load="impstats" interval="60" format="json" log.syslog="off"
  log.file="${o.statsFile}" resetCounters="off")
dyn_stats(name="rejected" resettable="off" maxCardinality="10000"
  unusedMetricLife="86400")
`
    : ''
  const allowRule = allow
    ? `
  # Sender allow-list, by the address the message came from.
  set $.ipnum = ip42num($fromhost-ip);
  if not (${allow}) then {
    set $.rejected = dyn_inc("rejected", $fromhost-ip);
    stop
  }
`
    : ''

  return `# Generated by the Log Collector package on every start. Do not edit:
# change the settings in Configure Receiver instead.

global(
  workDirectory="/var/spool/rsyslog"
  maxMessageSize="64k"
)

${inputs.join('\n')}
${allowList}
# secpath-replace turns "/" into "_" and makes ".", ".." and empty names safe,
# so a sender can never write outside its own folder.
template(name="dayFile" type="string"
  string="${o.logsDir}/%$.folder:::lowercase,secpath-replace%/%$year%-%$month%-%$day%.log")

template(name="line" type="string"
  string="%timegenerated:::date-rfc3339% %fromhost-ip% %syslogfacility-text%.%syslogseverity-text% %hostname% %$.tag%%msg:::sp-if-no-1st-sp%%msg:::drop-last-lf%\\n")

# Messages from the network: one file per sender per day.
ruleset(name="remote") {${allowRule}
  ${FOLDER_RULES[o.folderNaming]}

  # "program[pid]:" for every message. RFC 5424 carries the program and the
  # process id as separate fields with no colon; RFC 3164 usually has the
  # colon already.
  if $protocol-version == "1" then {
    if $procid != "-" and $procid != "" then {
      set $.tag = $app-name & "[" & $procid & "]:";
    } else {
      set $.tag = $app-name & ":";
    }
  } else if $syslogtag == "" or re_match($syslogtag, ':$') then {
    set $.tag = $syslogtag;
  } else {
    set $.tag = $syslogtag & ":";
  }

  action(
    type="omfile"
    dynaFile="dayFile"
    template="line"
    createDirs="on"
    dirCreateMode="0755"
    fileCreateMode="0644"
    dynaFileCacheSize="200"
    closeTimeout="10"
  )
}

# rsyslog's own messages (errors, warnings) go to stderr, which StartOS shows
# in the service logs.
`
}
